"""Shared interfaces, evidence data transfer objects, and output schemas for AI providers."""

from abc import ABC, abstractmethod
from typing import Any, Literal
from pydantic import BaseModel, Field


class EvidenceItem(BaseModel):
    """An individual verified or observed evidence item."""

    source_type: Literal["readme", "demo", "user_notes", "web_research"]
    content: str
    category: str = "general"
    source_url: str | None = None
    verification_status: Literal["documented", "observed", "user_supplied", "external", "unverified"] = "documented"


class EvidencePack(BaseModel):
    """Aggregated evidence package submitted to the AI generator."""

    project_name: str
    repo_url: str
    demo_url: str | None = None
    user_notes: str | None = None
    items: list[EvidenceItem] = Field(default_factory=list)


class PostPreferences(BaseModel):
    """User preferences for post tone, length, hashtags, and formatting."""

    style: Literal["professional", "developer", "showcase", "learning"] = "professional"
    language: str = "English"
    target_audience: str = "Software Engineers, Tech Leads, Engineering Managers"
    max_length: int = 2000
    custom_instructions: str = ""
    hashtag_prefs: str = "#Python #SoftwareEngineering #OpenSource #AI"
    include_links: bool = True
    include_screenshot: bool = True


class GeneratedDraftOutput(BaseModel):
    """Standardized structured output generated by any active AI provider."""

    post_text: str
    hashtags: list[str] = Field(default_factory=list)
    project_links: list[str] = Field(default_factory=list)
    suggested_media: str | None = None
    evidence_references: list[str] = Field(default_factory=list)
    unverified_cautions: list[str] = Field(default_factory=list)


class AIProviderError(Exception):
    """Base exception for AI provider initialization, connectivity, or generation errors."""
    pass


class LLMProvider(ABC):
    """Abstract interface shared by all AI providers (Cloud API and Local LLM)."""

    @abstractmethod
    def validate_configuration(self) -> tuple[bool, str]:
        """Validate provider configuration settings without initiating a network/model load."""
        pass

    @abstractmethod
    async def test_connection(self) -> tuple[bool, str]:
        """Test API connectivity or model availability."""
        pass

    @abstractmethod
    async def generate_linkedin_draft(
        self, evidence: EvidencePack, preferences: PostPreferences
    ) -> GeneratedDraftOutput:
        """Generate a structured LinkedIn draft based strictly on the provided evidence pack."""
        pass

    @abstractmethod
    def estimate_resources(self) -> dict[str, Any]:
        """Return memory, token limit, or resource usage estimates."""
        pass

    @abstractmethod
    def close(self) -> None:
        """Release any active connections or model memory."""
        pass
